// 规则 ⑤：看图/看字旁白解说员病
//
// 出处：
//   第二卷·「福音践行」第 5 条：彻底斩杀「看图/看字旁白解说员病」
//     原句举例：“这只猫抱着枕头睡得挺香”“口水都快滴到屏幕上了”
//   第三幕 · 病历 04「症状A：看见表情包，必把画面内容当视障解说复述一遍」
//
// 病根：人类长着眼睛，不需要 AI 复述画面；要的是你的反应和玩梗。
import { findAll, hit } from "./_helpers.mjs";

const RULES = [
  {
    // 明确的画面指代：图中 / 画面里 / 截图上 / 照片里……
    // 注意：「这张图」单独出现不算——「笑死，这张图我可以看一天」是人类正常感叹。
    re: /(图[中里上]|画面[中里上]|照片[中里上]|截图[中里上]|图片[中里上]|截图里|照片里)/g,
    severity: 1,
    kind: "画面指代",
    reason: "上来就指认画面内容（图中/画面里），是旁白解说员的标准起手",
  },
  {
    // 干巴巴的视觉描述：抱着枕头 / 睡得挺香 / 口水滴到屏幕……
    re: /(抱着枕头|睡得挺香|睡得正香|口水(都|快|差点)?(快)?滴|滴到屏幕|望天|呆萌|蹲在|躺在|趴在|盯着镜头|举着|比了个|表情(很|看起来)|嘴角(微微)?上扬|写着.{0,6}[」”"])/g,
    severity: 0.85,
    kind: "视觉描述",
    reason: "干巴巴复述画面细节（姿势/表情/文字），人类不需要旁白翻译机",
  },
  {
    // 把表情包当阅读理解做：「这个表情的意思是……」
    re: /(这个|这张|那只)?(表情包|图)(的意思|想表达|是在说|代表)/g,
    severity: 0.9,
    kind: "表情解读",
    reason: "给表情包做阅读理解，是机器把图当文字处理的典型症状",
  },
];

export default {
  id: "picture-narration",
  name: "看图旁白",
  shortName: "看图旁白",
  weight: 1.25,
  source: "第二卷·第5条 · 第三幕病历04",
  description:
    "对着图片复述画面内容（这只猫抱着枕头…），当「画面文字翻译机」。",
  detect(text) {
    const hits = [];
    for (const r of RULES) {
      for (const m of findAll(r.re, text)) {
        hits.push(hit(m.start, m.end, r.severity, r.reason, { kind: r.kind }));
      }
    }
    return hits;
  },
};
